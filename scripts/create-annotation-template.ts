import * as fs from 'fs';
import * as path from 'path';
import { PROCCTRL_TAXONOMY, PROCCTRL_DEFECT_KEYS } from '../src/benchmark/ProcCtrlScorecard';
import { ObservedTrajectoryRecord } from '../src/benchmark/ObservedBenchmarkExperiments';

/**
 * 从已评测轨迹生成过程级标注模板。
 *
 * 输出**不是**人工标注数据：所有 judgment 留空，仅供两名标注者按
 * docs/annotation_protocol.md 填写。脚本会同时输出一份 long-format CSV
 * worklist，便于线下标注或导入表格工具。
 *
 * 用法：
 *   npx ts-node scripts/create-annotation-template.ts \
 *     --records output/runs/<system>/trajectory-records.jsonl \
 *     --output output/annotations/template.json \
 *     --limit 200
 */

type Args = Record<string, string>;

function parseArgs(argv: string[]): Args {
  const parsed: Args = {};
  for (let index = 0; index < argv.length; index++) {
    const token = argv[index];
    if (!token.startsWith('--')) continue;
    parsed[token.slice(2)] =
      argv[index + 1] && !argv[index + 1].startsWith('--') ? argv[++index] : 'true';
  }
  return parsed;
}

function readJsonl(filePath: string): ObservedTrajectoryRecord[] {
  return fs
    .readFileSync(filePath, 'utf-8')
    .split('\n')
    .filter((line) => line.trim().length > 0)
    .map((line) => JSON.parse(line) as ObservedTrajectoryRecord);
}

function csvEscape(value: unknown): string {
  const text = value === null || typeof value === 'undefined' ? '' : String(value);
  return /[",\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
}

function writeCsv(rows: Array<Record<string, unknown>>, outPath: string): void {
  if (rows.length === 0) {
    fs.writeFileSync(outPath, '', 'utf-8');
    return;
  }
  const header = Object.keys(rows[0]);
  const lines = [header.join(',')];
  for (const row of rows) {
    lines.push(header.map((key) => csvEscape(row[key])).join(','));
  }
  fs.writeFileSync(outPath, `${lines.join('\n')}\n`, 'utf-8');
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  if (!args.records) {
    throw new Error('Missing --records (comma-separated trajectory-records.jsonl paths).');
  }
  const recordPaths = args.records
    .split(',')
    .map((value) => value.trim())
    .filter(Boolean)
    .map((value) => path.resolve(value));
  const records = recordPaths.flatMap(readJsonl);

  const seen = new Set<string>();
  const selected: ObservedTrajectoryRecord[] = [];
  for (const record of records) {
    const key = record.rawPath || `${record.benchmark}/${record.taskId}/${record.trialId}`;
    if (seen.has(key)) continue;
    if (args.benchmark && record.benchmark !== args.benchmark) continue;
    if (args.system && record.variant !== args.system) continue;
    seen.add(key);
    selected.push(record);
    if (args.limit && selected.length >= Number(args.limit)) break;
  }

  const outPath = path.resolve(args.output || 'output/annotations/template.json');
  fs.mkdirSync(path.dirname(outPath), { recursive: true });

  const cases = selected.map((record) => ({
    caseId: `${record.benchmark}/${record.taskId}/${record.trialId || 'single'}`,
    benchmark: record.benchmark,
    taskId: record.taskId,
    trialId: record.trialId || 'single',
    system: record.variant,
    success: record.success,
    rawPath: record.rawPath,
    annotations: {},
  }));

  const annotationSet = {
    schemaVersion: 'procctrlbench-annotation-v1',
    description:
      'TEMPLATE ONLY — generated by scripts/create-annotation-template.ts. ' +
      'No human judgments are present. Fill annotatorA/annotatorB (and adjudicated on disagreement) ' +
      'for all 11 defects before using this file as --annotations.',
    template: true,
    cases,
  };
  fs.writeFileSync(outPath, `${JSON.stringify(annotationSet, null, 2)}\n`, 'utf-8');

  const worklist = selected.flatMap((record) =>
    PROCCTRL_TAXONOMY.map((spec) => ({
      caseId: `${record.benchmark}/${record.taskId}/${record.trialId || 'single'}`,
      benchmark: record.benchmark,
      taskId: record.taskId,
      trialId: record.trialId || 'single',
      system: record.variant,
      success: record.success ?? '',
      rawPath: record.rawPath,
      defect: spec.key,
      annotationKey: spec.paperName,
      annotatorA: '',
      annotatorB: '',
      adjudicated: '',
      evidence: '',
      exemptionRationale: '',
    }))
  );
  const worklistPath = outPath.replace(/\.json$/i, '-worklist.csv');
  writeCsv(worklist, worklistPath);

  const systems = new Set(selected.map((record) => record.variant));
  const benchmarks = new Set(selected.map((record) => record.benchmark));
  console.log(`Wrote annotation template: ${outPath}`);
  console.log(`Wrote annotation worklist: ${worklistPath}`);
  console.log(`Cases: ${cases.length}, systems: ${systems.size}, benchmarks: ${benchmarks.size}`);
  console.log(`Defect rows in worklist: ${worklist.length} (${cases.length} x ${PROCCTRL_DEFECT_KEYS.length})`);

  if (cases.length !== 200 || systems.size !== 11) {
    console.warn(
      `WARNING: the paper's annotated set is 200 cases across 11 systems; this template has ` +
        `${cases.length} cases across ${systems.size} system(s). It is a template, not the paper's set.`
    );
  }
}

try {
  main();
} catch (error) {
  console.error(error instanceof Error ? error.message : error);
  process.exit(1);
}